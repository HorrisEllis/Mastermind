'use strict';
// ═══════════════════════════════════════════════════════════════════
// VAULT RECOVERY — snapshot check + "no snapshot" fallback
//
// _showVaultMissingScreen() previously offered three options: recreate,
// choose a new folder, or manually pick a backup file. It never checked
// the app's own automatic snapshot system (VaultSnapshots — wired via
// IPC, never called from any UI). This adds that check, and — per the
// actual request — a real fallback when no snapshot exists: import a
// vault, use the default location, or go create a new identity, instead
// of a dead end.
// ═══════════════════════════════════════════════════════════════════

const assert = require('assert');
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const ROOT = path.resolve(__dirname, '..');

const results = [];
const pending = [];
function t(name, fn) {
  try { fn(); results.push({ name, ok: true }); console.log('  \u2713 ' + name); }
  catch (e) {
    results.push({ name, ok: false });
    console.log('  \u2717 ' + name + '\n      ' + (e.message || '').split('\n').join('\n      '));
  }
}
function at(name, fn) { pending.push({ name, fn }); }

function extractBetween(src, startMarker, endMarkerPattern) {
  const start = src.indexOf(startMarker);
  assert.ok(start > -1, startMarker + ' not found');
  const end = src.search(endMarkerPattern);
  assert.ok(end > start, 'end boundary not found after start');
  return src.slice(start, end);
}

const vaultSrc = fs.readFileSync(path.join(ROOT, 'foundation', 'vault', 'mastermind-vault.js'), 'utf8');
const engineSrc = fs.readFileSync(path.join(ROOT, 'nexus-engine.js'), 'utf8');

// _vaultUseDefaultLocation is the last function in this contiguous
// region; grab through the end of the file section by using a generous
// end marker just past it (the module-ready IIFE that follows everything).
const recoveryRegionSrc = extractBetween(
  vaultSrc,
  'function _showVaultMissingScreen(vaultPath, reason = \'missing\') {',
  /\n\/\/ ── Module ready signal/
);

// ── Every function this region's generated HTML calls via onclick must
// actually be defined somewhere in the extracted source (or a known
// external, like _ssShow/startupRoute, which live in nexus-engine.js and
// are called across the file boundary the same way pickStartupFolder()
// already is elsewhere in this codebase).
t('every onclick handler generated by this region resolves to a real function', () => {
  const KNOWN_EXTERNAL = new Set(['_ssShow', 'startupRoute', 'pickStartupFolder']);
  const definedHere = new Set(
    [...recoveryRegionSrc.matchAll(/^(?:async )?function (\w+)/gm)].map(m => m[1])
  );
  const called = [...recoveryRegionSrc.matchAll(/onclick="([a-zA-Z_$][\w$]*)\(/g)].map(m => m[1]);
  assert.ok(called.length > 5, 'sanity check: this region should generate several buttons');
  const dead = called.filter(fn => !definedHere.has(fn) && !KNOWN_EXTERNAL.has(fn));
  assert.deepStrictEqual(dead, [], 'dead onclick handlers found: ' + dead.join(', '));
});

t('loginSubmit routes the v5-salt-absent case to the recovery screen, not a dead end', () => {
  const idx = engineSrc.indexOf("v5 vault and its salt is not on this machine");
  assert.ok(idx > -1, 'the v5-salt-absent error message should still exist');
  const nearby = engineSrc.slice(idx, idx + 900);
  assert.ok(/_showVaultMissingScreen\(vaultPath,\s*'legacy-salt-absent'\)/.test(nearby),
    'this branch must hand off to the recovery screen instead of just re-enabling the button');
});

function makeSandbox(nxapiOverrides) {
  const store = {};
  const makeEl = (id) => {
    if (!store[id]) store[id] = {
      id, style: {}, textContent: '', innerHTML: '', className: '',
      classList: { add() {}, remove() {}, toggle() {} },
      appendChild(child) { this._appended = this._appended || []; this._appended.push(child); },
      querySelectorAll: () => [],
      remove() {},
    };
    return store[id];
  };
  const calls = { startupRoute: 0, ssShow: [] };
  const sandbox = {
    console,
    document: {
      getElementById: (id) => makeEl(id),
      createElement: () => makeEl('__created__' + Math.random()),
      querySelectorAll: () => [],
    },
    escH: (s) => String(s == null ? '' : s).replace(/[&<>"']/g, c => ({ '&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;' }[c])),
    NX_CONFIG: {},
    AUTH: { username: null },
    MMLog: { info() {}, warn() {}, error() {} },
    MM_BUS: { emit() {} },
    _lsGet: () => null,
    _lsSet: () => {},
    _authLoadMeta: () => null,
    setTimeout: (fn) => fn(), // run "deferred" work immediately for the test
    startupRoute: () => { calls.startupRoute++; },
    _ssShow: (id, step) => { calls.ssShow.push({ id, step }); },
  };
  sandbox.window = { NXAPI: Object.assign({
    openFileDialog: async () => null,
    readFile: async () => null,
    vaultWrite: async () => ({ ok: false }),
    snapshotList: async () => ({ ok: true, snapshots: [] }),
    snapshotRestore: async () => ({ ok: false }),
    defaultFolder: async () => '/home/user/Documents/MASTERMIND',
    vaultExists: async () => false,
    setDataDir: async () => true,
  }, nxapiOverrides || {}) };
  vm.createContext(sandbox);
  return { sandbox, store: () => store, calls };
}

// ── _showVaultMissingScreen: reason text ─────────────────────────────

t('the legacy-salt-absent reason gets real explanatory text, not the generic fallback', () => {
  const { sandbox, store } = makeSandbox();
  vm.runInContext(recoveryRegionSrc, sandbox);
  vm.runInContext('_showVaultMissingScreen', sandbox)('/data/mastermind.vault', 'legacy-salt-absent');
  const html = store()['ss-vault-missing'].innerHTML;
  assert.ok(/older-format vault/i.test(html));
  assert.ok(!/Vault is unavailable\./.test(html), 'should not fall through to the generic reason text');
});

t('the screen now offers a RESTORE FROM SNAPSHOT option distinct from the manual file picker', () => {
  const { sandbox, store } = makeSandbox();
  vm.runInContext(recoveryRegionSrc, sandbox);
  vm.runInContext('_showVaultMissingScreen', sandbox)('/data/mastermind.vault', 'missing');
  const html = store()['ss-vault-missing'].innerHTML;
  assert.ok(html.includes('RESTORE FROM SNAPSHOT'));
  assert.ok(html.includes('RESTORE FROM BACKUP FILE'));
});

// ── _vaultCheckSnapshots: snapshots present ──────────────────────────

at('when snapshots exist, they are listed newest-looking-first with restore buttons', async () => {
  const snaps = [
    { name: 'a.vault', ts: 1000, saveCount: 3, hash12: 'aaa111', malformed: false },
    { name: 'b.vault', ts: 2000, saveCount: 5, hash12: 'bbb222', malformed: false },
  ];
  const { sandbox, store } = makeSandbox({
    snapshotList: async () => ({ ok: true, snapshots: snaps }),
  });
  vm.runInContext(recoveryRegionSrc, sandbox);
  await vm.runInContext('_vaultCheckSnapshots', sandbox)('/data/mastermind.vault');
  const html = store()['ss-vault-missing'].innerHTML || '';
  const appended = (store()['ss-vault-missing']._appended || []).map(e => e.innerHTML).join('\n');
  const combined = html + appended;
  assert.ok(/2 SNAPSHOTS FOUND/.test(combined));
  assert.ok(combined.includes("_vaultRestoreSnapshot('a.vault'"));
  assert.ok(combined.includes("_vaultRestoreSnapshot('b.vault'"));
});

at('when NO snapshots exist, the no-snapshot choice is shown instead of an empty list', async () => {
  const { sandbox, store } = makeSandbox({
    snapshotList: async () => ({ ok: true, snapshots: [] }),
  });
  vm.runInContext(recoveryRegionSrc, sandbox);
  await vm.runInContext('_vaultCheckSnapshots', sandbox)('/data/mastermind.vault');
  const appended = (store()['ss-vault-missing']._appended || []).map(e => e.innerHTML).join('\n');
  assert.ok(/NO SNAPSHOTS FOUND/.test(appended));
  assert.ok(appended.includes('IMPORT A VAULT'));
  assert.ok(appended.includes('USE DEFAULT LOCATION'));
  assert.ok(appended.includes('CREATE A NEW IDENTITY'));
});

at('a snapshotList IPC failure is treated the same as "none found", not a crash', async () => {
  const { sandbox, store } = makeSandbox({
    snapshotList: async () => { throw new Error('ipc exploded'); },
  });
  vm.runInContext(recoveryRegionSrc, sandbox);
  await vm.runInContext('_vaultCheckSnapshots', sandbox)('/data/mastermind.vault');
  const appended = (store()['ss-vault-missing']._appended || []).map(e => e.innerHTML).join('\n');
  assert.ok(/NO SNAPSHOTS FOUND/.test(appended));
});

// ── _vaultRestoreSnapshot ────────────────────────────────────────────

at('restoring a snapshot successfully re-routes startup', async () => {
  const { sandbox, store, calls } = makeSandbox({
    snapshotRestore: async () => ({ ok: true, saveCount: 4 }),
  });
  vm.runInContext(recoveryRegionSrc, sandbox);
  await vm.runInContext('_vaultRestoreSnapshot', sandbox)('a.vault', '/data/mastermind.vault');
  assert.strictEqual(calls.startupRoute, 1);
  assert.ok(/restored/i.test(store()['vault-missing-status'].textContent));
});

at('a failed snapshot restore reports the error and does NOT re-route', async () => {
  const { sandbox, store, calls } = makeSandbox({
    snapshotRestore: async () => ({ ok: false, error: 'checksum mismatch' }),
  });
  vm.runInContext(recoveryRegionSrc, sandbox);
  await vm.runInContext('_vaultRestoreSnapshot', sandbox)('a.vault', '/data/mastermind.vault');
  assert.strictEqual(calls.startupRoute, 0);
  assert.ok(/checksum mismatch/.test(store()['vault-snapshot-error'].textContent));
});

// ── _vaultUseDefaultLocation ──────────────────────────────────────────

at('default location: a vault already there routes to login (startupRoute), not setup', async () => {
  const { sandbox, calls } = makeSandbox({
    vaultExists: async () => true,
  });
  vm.runInContext(recoveryRegionSrc, sandbox);
  await vm.runInContext('_vaultUseDefaultLocation', sandbox)();
  assert.strictEqual(calls.startupRoute, 1);
  assert.strictEqual(calls.ssShow.length, 0);
  assert.strictEqual(sandbox.NX_CONFIG.dataDir, '/home/user/Documents/MASTERMIND');
});

at('default location: nothing there routes to identity creation (step 1), not a dead end', async () => {
  const { sandbox, calls } = makeSandbox({
    vaultExists: async () => false,
  });
  vm.runInContext(recoveryRegionSrc, sandbox);
  await vm.runInContext('_vaultUseDefaultLocation', sandbox)();
  assert.strictEqual(calls.startupRoute, 0);
  assert.deepStrictEqual(calls.ssShow, [{ id: 'ss-setup', step: 1 }]);
});

async function run() {
  console.log('\nVAULT RECOVERY — snapshots + no-snapshot fallback\n');
  for (const { name, fn } of pending) {
    try { await fn(); results.push({ name, ok: true }); console.log('  \u2713 ' + name); }
    catch (e) {
      results.push({ name, ok: false });
      console.log('  \u2717 ' + name + '\n      ' + (e.message || '').split('\n').join('\n      '));
    }
  }
  const fails = results.filter(r => !r.ok);
  console.log('\nvault-recovery: ' + (results.length - fails.length) + '/' + results.length + ' passed');
  process.exitCode = fails.length ? 1 : 0;
}
run();
